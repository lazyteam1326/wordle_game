// Get word of the day based on date
export function getWordOfDay(): string {
  const epoch = new Date(2024, 0, 1); // January 1, 2024
  const now = new Date();
  const diff = now.getTime() - epoch.getTime();
  const dayIndex = Math.floor(diff / (1000 * 60 * 60 * 24));
  return ANSWER_WORDS[dayIndex % ANSWER_WORDS.length].toUpperCase();
}

// Get a random word for infinite mode
export function getRandomWord(): string {
  const index = Math.floor(Math.random() * ANSWER_WORDS.length);
  return ANSWER_WORDS[index].toUpperCase();
}

// Check if a word is valid
export function isValidWord(word: string): boolean {
  return VALID_GUESSES.includes(word.toLowerCase());
}

// Get today's date string
export function getTodayString(): string {
  return new Date().toLocaleDateString('en-US', { 
    weekday: 'long', 
    year: 'numeric', 
    month: 'long', 
    day: 'numeric' 
  });
}
